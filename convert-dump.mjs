// Converts the phpMyAdmin/MySQL dump (luna_transfer.sql) into a SQL file that Cloudflare D1 can import.
//   node scripts/convert-dump.mjs luna_transfer.sql d1-data.sql
// Keeps: users, links, files, activity, transfers, orders. Skips temporary tables (uploads in progress, tokens, rate limits, sessions).
// Old files get store=0 (one whole object in R2 at files/<id>); see scripts/upload-legacy-files.mjs.
import { readFileSync, writeFileSync } from 'node:fs';

const [, , inFile, outFile = 'd1-data.sql'] = process.argv;
if (!inFile) { console.error('Usage: node scripts/convert-dump.mjs luna_transfer.sql [d1-data.sql]'); process.exit(1); }
const sql = readFileSync(inFile, 'utf8');
const KEEP = ['users', 'links', 'files', 'activity', 'transfers', 'orders'];

// Reads one MySQL string literal starting at s[i] === "'" and returns [value, nextIndex].
function readString(s, i) {
  let o = ''; i++;
  for (;;) {
    const ch = s[i];
    if (ch === undefined) throw new Error('unterminated string');
    if (ch === '\\') {
      const n = s[i + 1]; i += 2;
      o += ({ n: '\n', r: '\r', t: '\t', 0: '\0', Z: '\x1a', b: '\b' })[n] ?? n; // \' \" \\ and anything else -> the character itself
    } else if (ch === "'") { if (s[i + 1] === "'") { o += "'"; i += 2; } else return [o, i + 1]; }
    else { o += ch; i++; }
  }
}
function parseValues(s, i) { // s[i] is just after "VALUES"; returns [rows, nextIndex]
  const rows = [];
  for (;;) {
    while (/\s/.test(s[i])) i++;
    if (s[i] !== '(') throw new Error('expected ( at ' + i);
    i++; const row = [];
    for (;;) {
      while (/\s/.test(s[i])) i++;
      if (s[i] === "'") { const [v, n] = readString(s, i); row.push(v); i = n; }
      else { const m = /^(NULL|-?\d+(?:\.\d+)?(?:[eE][+-]?\d+)?)/i.exec(s.slice(i, i + 40)); if (!m) throw new Error('bad value near ' + s.slice(i, i + 30)); row.push(/^null$/i.test(m[1]) ? null : Number(m[1])); i += m[1].length; }
      while (/\s/.test(s[i])) i++;
      if (s[i] === ',') { i++; continue; }
      if (s[i] === ')') { i++; break; }
      throw new Error('bad row near ' + s.slice(i, i + 30));
    }
    rows.push(row);
    while (/\s/.test(s[i])) i++;
    if (s[i] === ',') { i++; continue; }
    if (s[i] === ';') return [rows, i + 1];
    throw new Error('bad separator near ' + s.slice(i, i + 30));
  }
}
const lit = v => v === null ? 'NULL' : typeof v === 'number' ? String(v) : "'" + v.replaceAll("'", "''") + "'";

const data = {}; // table -> {cols, rows}
const re = /INSERT INTO `(\w+)` \(([^)]*)\) VALUES/g; let m;
while ((m = re.exec(sql))) {
  const [rows, end] = parseValues(sql, re.lastIndex);
  const cols = m[2].split(',').map(c => c.trim().replaceAll('`', ''));
  (data[m[1]] ??= { cols, rows: [] }).rows.push(...rows); re.lastIndex = end;
}
let out = '-- generated by convert-dump.mjs\n', counts = {};
// legacy: an admins table from very old versions; only used if users has no admin
if (data.admins && !(data.users?.rows ?? []).some(r => r[data.users.cols.indexOf('role')] === 'admin')) {
  const { cols, rows } = data.admins; const u = data.users ??= { cols: ['id', 'username', 'password_hash', 'role', 'active', 'created_at'], rows: [] };
  for (const r of rows) u.rows.push([r[cols.indexOf('id')], r[cols.indexOf('username')], r[cols.indexOf('password_hash')], 'admin', 1, r[cols.indexOf('created_at')]]);
}
for (const t of KEEP) {
  const d = data[t]; if (!d) { counts[t] = 0; continue; }
  const cols = t === 'files' ? [...d.cols, 'store'] : d.cols;
  for (const r of d.rows) out += `INSERT INTO ${t} (${cols.join(', ')}) VALUES (${(t === 'files' ? [...r, 0] : r).map(lit).join(', ')});\n`;
  counts[t] = d.rows.length;
}
writeFileSync(outFile, out);
console.log('Wrote', outFile, JSON.stringify(counts));
